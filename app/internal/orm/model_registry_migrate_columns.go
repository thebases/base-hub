package orm

// File overview:
// - Responsibility: column definition SQL, default-value normalisation and implicit JSONB defaults.
// - Key symbols: `columnDefinitionSQL`, `equalSchemaColumns`, `targetColumnForChange`, `compareColumnTypes`.

import (
	"fmt"
	"strings"

	"github.com/uptrace/bun"
	"github.com/uptrace/bun/migrate/sqlschema"
)

func columnDefinitionSQL(column sqlschema.Column) string {
	if column == nil {
		return ""
	}
	typeName := strings.TrimSpace(strings.ToLower(column.GetSQLType()))
	switch {
	case typeName == "":
		return ""
	case strings.HasPrefix(typeName, "varchar") || strings.HasPrefix(typeName, "character varying"):
		if n := column.GetVarcharLen(); n > 0 {
			typeName = fmt.Sprintf("varchar(%d)", n)
		} else {
			typeName = "varchar"
		}
	}
	parts := []string{typeName}
	if defaultValue := strings.TrimSpace(column.GetDefaultValue()); defaultValue != "" {
		parts = append(parts, "DEFAULT "+defaultValue)
	} else if column.GetIsIdentity() || column.GetIsAutoIncrement() {
		parts = append(parts, "GENERATED BY DEFAULT AS IDENTITY")
	}
	return strings.Join(parts, " ")
}

func equalSchemaColumns(db *bun.DB, left, right sqlschema.Column) bool {
	return compareColumnTypes(db, left, right) &&
		normalizeColumnDefaultValue(left.GetDefaultValue(), left.GetSQLType()) == normalizeColumnDefaultValue(right.GetDefaultValue(), right.GetSQLType()) &&
		left.GetIsNullable() == right.GetIsNullable() &&
		left.GetIsAutoIncrement() == right.GetIsAutoIncrement() &&
		left.GetIsIdentity() == right.GetIsIdentity()
}

func targetColumnForChange(db *bun.DB, current, target sqlschema.Column) sqlschema.Column {
	if compareColumnTypes(db, current, target) {
		return &sqlschema.BaseColumn{
			Name:            target.GetName(),
			DefaultValue:    target.GetDefaultValue(),
			IsNullable:      target.GetIsNullable(),
			IsAutoIncrement: target.GetIsAutoIncrement(),
			IsIdentity:      target.GetIsIdentity(),
			SQLType:         current.GetSQLType(),
			VarcharLen:      current.GetVarcharLen(),
		}
	}
	return target
}

// compareColumnTypes compares the column types handled by this package.
func compareColumnTypes(db *bun.DB, left, right sqlschema.Column) bool {
	if db != nil {
		if inspector, ok := db.Dialect().(sqlschema.InspectorDialect); ok {
			return inspector.CompareType(left, right)
		}
	}
	return left.GetSQLType() == right.GetSQLType() && left.GetVarcharLen() == right.GetVarcharLen()
}

func normalizeColumnDefaultValue(defaultValue, sqlType string) string {
	defaultValue = strings.TrimSpace(defaultValue)
	if defaultValue == "" {
		return ""
	}
	if !strings.EqualFold(strings.TrimSpace(sqlType), "jsonb") {
		return defaultValue
	}
	defaultValue = strings.TrimSpace(strings.TrimSuffix(defaultValue, "::jsonb"))
	if defaultValue == "'{}'" || defaultValue == "{}" {
		return "'{}'::jsonb"
	}
	if defaultValue == "'[]'" || defaultValue == "[]" {
		return "'[]'::jsonb"
	}
	return defaultValue
}

func applyImplicitJSONBDefaultsToTable(metadata *ModelMetadata, table *sqlschema.BaseTable) *sqlschema.BaseTable {
	if metadata == nil || table == nil {
		return table
	}
	defaultColumns := implicitJSONBDefaultColumns(metadata)
	if len(defaultColumns) == 0 {
		return table
	}
	columns := table.GetColumns()
	for i, column := range columns {
		if column == nil {
			continue
		}
		columnName := strings.TrimSpace(column.GetName())
		if _, ok := defaultColumns[columnName]; !ok {
			continue
		}
		if !strings.EqualFold(strings.TrimSpace(column.GetSQLType()), "jsonb") {
			continue
		}
		if normalizeColumnDefaultValue(column.GetDefaultValue(), column.GetSQLType()) != "" {
			continue
		}
		// Keep the SQL default canonical so schema diffing matches PostgreSQL's
		// jsonb inspector output instead of planning the same change every boot.
		defaultValue := defaultValueForImplicitJSONBColumn(metadata, columnName)
		if defaultValue == "" {
			continue
		}
		columns[i] = cloneSchemaColumnWithDefault(column, defaultValue)
	}
	table.Columns = columns
	return table
}

func implicitJSONBDefaultColumns(metadata *ModelMetadata) map[string]struct{} {
	if metadata == nil {
		return nil
	}
	columns := make(map[string]struct{})
	for _, field := range metadata.Fields {
		if normalized := strings.TrimSpace(field.Default); normalized != "{}" && normalized != "[]" {
			continue
		}
		columnName := strings.TrimSpace(field.BunColumn)
		if columnName == "" {
			continue
		}
		columns[columnName] = struct{}{}
	}
	return columns
}

func defaultValueForImplicitJSONBColumn(metadata *ModelMetadata, columnName string) string {
	if metadata == nil {
		return ""
	}
	columnName = strings.TrimSpace(columnName)
	if columnName == "" {
		return ""
	}
	for _, field := range metadata.Fields {
		if strings.TrimSpace(field.BunColumn) != columnName {
			continue
		}
		switch strings.TrimSpace(field.Default) {
		case "{}":
			return "'{}'::jsonb"
		case "[]":
			return "'[]'::jsonb"
		}
	}
	return ""
}

func cloneSchemaColumns(columns []sqlschema.Column) []sqlschema.Column {
	if len(columns) == 0 {
		return nil
	}
	cloned := make([]sqlschema.Column, 0, len(columns))
	for _, column := range columns {
		cloned = append(cloned, cloneSchemaColumnWithDefault(column, column.GetDefaultValue()))
	}
	return cloned
}

// sqlReadyColumnDefault repairs a target column built by bun's
// BunModelInspector before it is embedded in a migrate.Operation. Bun's own
// inspector (migrate/sqlschema.exprOrLiteral) strips the surrounding quotes
// off any `default:'...'` struct tag when it builds the column's canonical
// DefaultValue — harmless for diffing, since pgdialect's live-DB inspector
// reports the same stripped form for comparison. But pgdialect's
// AddColumnOp/ChangeColumnTypeOp migrator (dialect/pgdialect/alter_table.go)
// writes that value verbatim after "DEFAULT "/"SET DEFAULT " with no
// re-quoting, so a stripped string default like "linear" becomes the bare
// SQL token `DEFAULT linear`, which Postgres parses as a column reference
// (SQLSTATE 0A000) instead of the intended text literal. Re-quote only on
// the copy handed to the operation so the unquoted canonical form used for
// diffing (equalSchemaColumns) stays untouched.
func sqlReadyColumnDefault(column sqlschema.Column) sqlschema.Column {
	if column == nil {
		return column
	}
	quoted := quoteBareTextualDefault(column.GetDefaultValue(), column.GetSQLType())
	if quoted == column.GetDefaultValue() {
		return column
	}
	return cloneSchemaColumnWithDefault(column, quoted)
}

// quoteBareTextualDefault wraps a bare textual default (e.g. "linear") back
// into a valid SQL string literal, leaving function calls, the NULL
// keyword, already-quoted values, and non-textual column types untouched.
func quoteBareTextualDefault(defaultValue, sqlType string) string {
	defaultValue = strings.TrimSpace(defaultValue)
	if defaultValue == "" || strings.HasPrefix(defaultValue, "'") {
		return defaultValue
	}
	if !isTextualSQLType(sqlType) {
		return defaultValue
	}
	if strings.Contains(defaultValue, "(") || strings.EqualFold(defaultValue, "null") {
		return defaultValue
	}
	return "'" + strings.ReplaceAll(defaultValue, "'", "''") + "'"
}

func isTextualSQLType(sqlType string) bool {
	sqlType = strings.ToLower(strings.TrimSpace(sqlType))
	switch {
	case strings.HasPrefix(sqlType, "varchar"),
		strings.HasPrefix(sqlType, "character varying"),
		strings.HasPrefix(sqlType, "character"),
		strings.HasPrefix(sqlType, "char"),
		strings.HasPrefix(sqlType, "text"),
		strings.HasPrefix(sqlType, "uuid"),
		strings.HasPrefix(sqlType, "json"):
		// json/jsonb literals ({} / []) are stripped of quotes by bun the same way.
		return true
	default:
		return false
	}
}

func cloneSchemaColumnWithDefault(column sqlschema.Column, defaultValue string) sqlschema.Column {
	if column == nil {
		return nil
	}
	return &sqlschema.BaseColumn{
		Name:            column.GetName(),
		SQLType:         column.GetSQLType(),
		VarcharLen:      column.GetVarcharLen(),
		DefaultValue:    defaultValue,
		IsNullable:      column.GetIsNullable(),
		IsAutoIncrement: column.GetIsAutoIncrement(),
		IsIdentity:      column.GetIsIdentity(),
	}
}

// replacePrimaryKeyColumn replaces the primary key column handled by this package.
func replacePrimaryKeyColumn(table sqlschema.Table, oldName, newName string) {
	if table == nil {
		return
	}
	pk := table.GetPrimaryKey()
	if pk == nil {
		return
	}
	pk.Columns.Replace(oldName, newName)
}
