package models

// File overview:
// - Responsibility: defines built-in runtime model metadata and server-side behavior for sys model operation inside
//   the kernel model catalog — a per-model snapshot of the code-defined RuntimeMethod catalog (ModelSpec.RuntimeMethods
//   plus StandardHooks defaults), so operators can inspect which methods/actions each model exposes without reading Go.
// - Key symbols: `init`, `SysModelOperationRecord`, `SyncSysModelOperations`.
// - Pattern: Leans on metadata-driven registration so storage mapping, runtime methods, and behavior hooks stay
//   centralized instead of being scattered across handlers.

import (
	"context"
	"fmt"
	"sort"

	"git.thebase.vn/base_hub/internal/orm"
	"github.com/uptrace/bun"
)

// SysModelOperationRecord stores one runtime method/action declared in code
// for a model (RuntimeMethod on its ModelSpec, including inherited
// StandardHooks defaults), so the operation catalog stays queryable per
// model instead of only living inside the opaque sys_model.json_dto blob.
type SysModelOperationRecord struct {
	bun.BaseModel `bun:"table:sys_model_operation,alias:sys_model_operation"`
	orm.MetadataBaseModel
	Name           string `bun:"name" json:"name" meta:"index,unique,label:Name,help:Stores the model.method identifier for this record."`
	ModelName      string `bun:"model_name" json:"model_name" meta:"index,label:Model Name,help:Stores the model this operation belongs to."`
	MethodName     string `bun:"method_name" json:"method_name" meta:"index,label:Method Name,help:Stores the runtime method or action name defined in code for this model."`
	Module         string `bun:"module" json:"module" meta:"index,label:Module,help:Stores the module that registered this model."`
	IsPublic       bool   `bun:"is_public" json:"is_public" meta:"label:Is Public,help:Controls whether this operation is callable via the public runtime RPC surface."`
	IsModelOnly    bool   `bun:"is_model_only" json:"is_model_only" meta:"label:Is Model Only,help:Controls whether this operation only accepts model-level calls without a record id."`
	IsReadOnly     bool   `bun:"is_read_only" json:"is_read_only" meta:"label:Is Read Only,help:Controls whether this operation never mutates state."`
	UsesPathID     bool   `bun:"uses_path_id" json:"uses_path_id" meta:"label:Uses Path ID,help:Controls whether this operation requires a record id in the request path."`
	OperationIndex int    `bun:"operation_index" json:"operation_index" meta:"label:Operation Index,help:Stores the declared order of this operation within its model's runtime method list."`
}

const SysModelOperationModelName = "sys.model.operation"

var SysModelOperationModelSpec = orm.ModelSpec{
	Name:        SysModelOperationModelName,
	Label:       "Model Operations",
	Description: "Runtime method/action catalog reflected from each model's code-defined RuntimeMethods (ModelSpec.RuntimeMethods plus StandardHooks defaults); rows are generated by SyncSysModelOperations and are read-only through the runtime API",
	Definition:  orm.ModelDefinition(SysModelOperationModelName, (*SysModelOperationRecord)(nil)),
	RuntimeMethods: []orm.RuntimeMethod{
		{Name: "create", Public: true, ModelOnly: true, Call: rejectSysModelOperationWrite},
		{Name: "write", Public: true, UsesPathID: true, Call: rejectSysModelOperationWrite},
		{Name: "unlink", Public: true, UsesPathID: true, Call: rejectSysModelOperationWrite},
	},
}

var SysModelOperationModel = orm.Define[SysModelOperationRecord](&Models, 65, SysModelOperationModelSpec)

// rejectSysModelOperationWrite blocks every mutating runtime call on
// sys.model.operation. Rows are generated exclusively by
// SyncSysModelOperations (full delete-then-reinsert from the live model
// registry at boot) — an API/UI edit would be silently discarded on the next
// sync.
func rejectSysModelOperationWrite(context.Context, *orm.ModelMetadata, []string, []any, map[string]any) (any, error) {
	return nil, fmt.Errorf("sys.model.operation is read-only; rows are generated from the model registry by SyncSysModelOperations")
}

// SyncSysModelOperations rewrites the operation metadata snapshot from the
// registered runtime models so startup leaves one auditable source of truth.
// Operations have no user-added custom rows — every row is a direct reflection
// of code state — but rows are upserted by name (not delete-then-reinserted) so
// their ids stay stable for sys.model.action references.
func SyncSysModelOperations(ctx context.Context, db *bun.DB, models []orm.ModelMetadata) error {
	if db == nil {
		return nil
	}

	rows := buildSysModelOperationRows(models)
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer func() {
		if err != nil {
			_ = tx.Rollback()
		}
	}()

	existingRows, err := loadSysModelOperationRows(ctx, tx)
	if err != nil {
		return err
	}

	// Reconcile by name instead of delete-then-reinsert so row ids stay stable across
	// boots: sys.model.action.operation_id references these rows, and a full rewrite would
	// null every reference (ondelete SET NULL) on each restart.
	if err = upsertSysModelOperationRows(ctx, tx, existingRows, rows); err != nil {
		return err
	}
	if err = logSysModelOperationSyncChanges(ctx, tx, existingRows, rows); err != nil {
		return err
	}
	return tx.Commit()
}

// upsertSysModelOperationRows reconciles the table with the registry keyed by the operation
// name: unchanged rows are left alone, changed rows are updated in place (keeping their id),
// new operations are inserted and vanished ones deleted. The diff runs in Go against the rows
// already loaded for change logging, so it needs no DB unique constraint on name (the column
// only carries a plain index) and a typical boot issues no writes at all. Inserted rows get
// their ids back from the INSERT, so `rows` is complete for the change log afterwards.
func upsertSysModelOperationRows(ctx context.Context, tx bun.Tx, existing, rows []SysModelOperationRecord) error {
	existingByName := make(map[string]SysModelOperationRecord, len(existing))
	for _, row := range existing {
		existingByName[row.Name] = row
	}
	inserts := make([]*SysModelOperationRecord, 0)
	for i := range rows {
		current, ok := existingByName[rows[i].Name]
		delete(existingByName, rows[i].Name)
		if !ok {
			inserts = append(inserts, &rows[i])
			continue
		}
		rows[i].ID = current.ID
		rows[i].CreatedAt = current.CreatedAt
		if sysModelOperationRowUnchanged(current, rows[i]) {
			rows[i].UpdatedAt = current.UpdatedAt
			continue
		}
		if _, err := tx.NewUpdate().Model(&rows[i]).
			Column("model_name", "method_name", "module", "is_public", "is_model_only", "is_read_only", "uses_path_id", "operation_index").
			Set("updated_at = now()").
			WherePK().Exec(ctx); err != nil {
			return err
		}
	}
	if len(inserts) > 0 {
		if _, err := tx.NewInsert().Model(&inserts).Exec(ctx); err != nil {
			return err
		}
	}
	// Whatever is left in existingByName is no longer declared in code.
	if len(existingByName) == 0 {
		return nil
	}
	staleIDs := make([]int64, 0, len(existingByName))
	for _, row := range existingByName {
		staleIDs = append(staleIDs, row.ID)
	}
	_, err := tx.NewDelete().Model((*SysModelOperationRecord)(nil)).Where("id IN (?)", bun.In(staleIDs)).Exec(ctx)
	return err
}

// sysModelOperationRowUnchanged compares the code-derived columns only (ids/timestamps excluded).
func sysModelOperationRowUnchanged(a, b SysModelOperationRecord) bool {
	return a.ModelName == b.ModelName && a.MethodName == b.MethodName && a.Module == b.Module &&
		a.IsPublic == b.IsPublic && a.IsModelOnly == b.IsModelOnly && a.IsReadOnly == b.IsReadOnly &&
		a.UsesPathID == b.UsesPathID && a.OperationIndex == b.OperationIndex
}

// buildSysModelOperationRows builds the sys model operation rows handled by this package.
func buildSysModelOperationRows(models []orm.ModelMetadata) []SysModelOperationRecord {
	rows := make([]SysModelOperationRecord, 0)
	for _, model := range models {
		module := modelModuleName(model.Name)
		// Preserve RuntimeMethods slice order (already deterministic, sorted by
		// name in mergeRuntimeMethods) so the system table reflects registry
		// order for debugging and metadata export.
		for i, method := range model.RuntimeMethods {
			rows = append(rows, SysModelOperationRecord{
				Name:           model.Name + "." + method.Name,
				ModelName:      model.Name,
				MethodName:     method.Name,
				Module:         module,
				IsPublic:       method.Public,
				IsModelOnly:    method.ModelOnly,
				IsReadOnly:     method.ReadOnly,
				UsesPathID:     method.UsesPathID,
				OperationIndex: i,
			})
		}
	}
	return rows
}

// loadSysModelOperationRows loads the sys model operation rows handled by this package.
func loadSysModelOperationRows(ctx context.Context, db bun.IDB) ([]SysModelOperationRecord, error) {
	if db == nil {
		return nil, nil
	}
	rows := make([]SysModelOperationRecord, 0)
	if err := db.NewSelect().
		Model(&rows).
		OrderExpr("model_name ASC, operation_index ASC").
		Scan(ctx); err != nil {
		return nil, err
	}
	return rows, nil
}

// logSysModelOperationSyncChanges logs the sys model operation sync changes handled by this package.
func logSysModelOperationSyncChanges(ctx context.Context, db bun.IDB, beforeRows, afterRows []SysModelOperationRecord) error {
	beforeByName := make(map[string]SysModelOperationRecord, len(beforeRows))
	for _, row := range beforeRows {
		beforeByName[row.Name] = row
	}
	afterByName := make(map[string]SysModelOperationRecord, len(afterRows))
	for _, row := range afterRows {
		afterByName[row.Name] = row
	}

	names := make(map[string]struct{}, len(beforeByName)+len(afterByName))
	for name := range beforeByName {
		names[name] = struct{}{}
	}
	for name := range afterByName {
		names[name] = struct{}{}
	}

	orderedNames := make([]string, 0, len(names))
	for name := range names {
		orderedNames = append(orderedNames, name)
	}
	sort.Strings(orderedNames)

	for _, name := range orderedNames {
		before, hadBefore := beforeByName[name]
		after, hadAfter := afterByName[name]
		switch {
		case !hadBefore && hadAfter:
			if err := orm.LogModelChange(ctx, db, buildMetadataChangeLogEntry(ctx, SysModelOperationModelName, "create", "registry_sync", nil, sysModelOperationRecordMap(after))); err != nil {
				return err
			}
		case hadBefore && !hadAfter:
			if err := orm.LogModelChange(ctx, db, buildMetadataChangeLogEntry(ctx, SysModelOperationModelName, "unlink", "registry_sync", sysModelOperationRecordMap(before), nil)); err != nil {
				return err
			}
		case hadBefore && hadAfter:
			entry := buildMetadataChangeLogEntry(ctx, SysModelOperationModelName, "write", "registry_sync", sysModelOperationRecordMap(before), sysModelOperationRecordMap(after))
			if len(entry.ChangedFields) == 0 {
				continue
			}
			if err := orm.LogModelChange(ctx, db, entry); err != nil {
				return err
			}
		}
	}
	return nil
}

func sysModelOperationRecordMap(row SysModelOperationRecord) orm.RecordMap {
	return orm.RecordMap{
		"id":              row.ID,
		"name":            row.Name,
		"model_name":      row.ModelName,
		"method_name":     row.MethodName,
		"module":          row.Module,
		"is_public":       row.IsPublic,
		"is_model_only":   row.IsModelOnly,
		"is_read_only":    row.IsReadOnly,
		"uses_path_id":    row.UsesPathID,
		"operation_index": row.OperationIndex,
	}
}
