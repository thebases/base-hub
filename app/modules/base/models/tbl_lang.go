// createResLang keeps the list-payload create; defaults and validation run in prepareResLang.
func createResLang(ctx context.Context, model *orm.ModelMetadata, _ []string, args []any, kwargs map[string]any) (any, error) {
	return createRecordList(ctx, orm.RuntimeModelRef(ResLangModelName, model), args, kwargs)
}

// prepareResLang runs inside the guarded create/write. Create fills the defaults; write refuses a
// code change and deactivating a language still in use. Both normalise and validate the formats.
func prepareResLang(ctx context.Context, op orm.WriteOp) error {
	if op.Create {
		applyResLangDefaults(op.Values)
	} else if err := checkResLangWrite(ctx, op.IDs, op.Values); err != nil {
		return err
	}
	normalizeResLangClockFormat(op.Values)
	normalizeResLangDirection(op.Values)
	return validateResLangValues(op.Values)
}

// checkResLangWrite holds the write-only invariants that need the stored rows.
func checkResLangWrite(ctx context.Context, ids []string, values orm.RecordMap) error {
	if len(ids) == 0 {
		log.Errorf("tbl.lang.write requires ids")
		return orm.InvalidParamsf("tbl.lang.write requires ids")
	}
	rows, err := loadResLangRows(ctx, ids)
	if err != nil {
		return err
	}
	// A code may be re-cased/re-separated to its canonical form (en_US -> en_us, the
	// seed reimport after the language-code migration) but never changed to another language.
	if code, ok := stringFromAny(values["code"]); ok {
		for _, row := range rows {
			if strings.TrimSpace(code) != "" && i18n.NormalizeLang(row.Code) != i18n.NormalizeLang(code) {
				log.Errorf("tbl.lang: language code cannot be modified")
				return orm.InvalidParamsf("tbl.lang: language code cannot be modified")
			}
		}
	}
	if _, exists := values["active"]; exists && !boolValue(values["active"]) {
		codes := make([]string, 0, len(rows))
		for _, row := range rows {
			codes = append(codes, row.Code)
		}
		return ensureResLangNotInUse(ctx, codes)
	}
	return nil
}

func nameGetResLang(ctx context.Context, _ *orm.ModelMetadata, ids []string, _ []any, _ map[string]any) (any, error) {
	rows, err := loadResLangRows(ctx, ids)
	if err != nil {
		return nil, err
	}
	out := make([][2]any, 0, len(rows))
	for _, row := range rows {
		out = append(out, [2]any{row.ID, row.Name})
	}
	return out, nil
}

func nameSearchResLang(ctx context.Context, model *orm.ModelMetadata, _ []string, args []any, kwargs map[string]any) (any, error) {
	name := strings.TrimSpace(stringArg(args, 0))
	if keyword, ok := stringFromAny(kwargs["name"]); ok && strings.TrimSpace(keyword) != "" {
		name = strings.TrimSpace(keyword)
	}
	operator := firstNonEmpty(strings.TrimSpace(stringValue(kwargs["operator"])), "ilike")
	limit := int64Value(kwargs["limit"])
	if limit <= 0 {
		limit = 100
	}
	// A client call cannot list past server.maxReadLimit (plan T36).
	limit = int64(orm.ClampClientReadLimit(ctx, model, int(limit)))
	// Bind helper reads to the registered tbl_lang storage table so custom Bun
	// queries do not fall back to Bun's inferred tbl_lang_records table name.
	query := resLangSelectQuery(ctx, (*ResLangRecord)(nil)).
		Column("id", "name", "code", "iso_code", "active")
	if !boolValueOrDefault(kwargs["active_test_false"], false) {
		query = query.Where("active IS TRUE")
	}
	if name != "" {
		clause, value := resLangLikeClause(operator, name)
		query = query.WhereGroup(" AND ", func(q *bun.SelectQuery) *bun.SelectQuery {
			return q.
				Where("name "+clause, value).
				WhereOr("code "+clause, value).
				WhereOr("iso_code "+clause, value)
		})
	}
	rows := []ResLangRecord{}
	if err := query.OrderExpr("active DESC, name ASC").Limit(int(limit)).Scan(ctx, &rows); err != nil {
		return nil, err
	}
	out := make([][2]any, 0, len(rows))
	for _, row := range rows {
		out = append(out, [2]any{row.ID, row.Name})
	}
	return out, nil
}

