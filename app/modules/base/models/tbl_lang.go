// ResLangRecord ports the tbl.lang reference metadata so formatting, locale
// selection, and language dropdowns follow the same contract as the source
// model set from `.agents/temp/models`.
type ResLangRecord struct {
	orm.BaseModel
	Name         string `bun:"name" json:"name" meta:"index,unique,label:Name,help:Stores the human readable name for this record."`
	Code         string `bun:"code" json:"code" meta:"index,unique,label:Code,help:Stores the code value for this record."`
	ISOCode      string `bun:"iso_code" json:"iso_code" meta:"index,label:ISO Code,help:Stores the iso code value for this record."`
	Direction    string `bun:"direction" json:"direction" meta:"label:Direction,help:Stores the direction value for this record."`
	DateFormat   string `bun:"date_format" json:"date_format" meta:"label:Date Format,help:Stores the date format value for this record."`
	TimeFormat   string `bun:"time_format" json:"time_format" meta:"label:Time Format,help:Stores the time format value for this record."`
	WeekStart    string `bun:"week_start" json:"week_start" meta:"label:Week Start,help:Stores the week start value for this record."`
	Grouping     string `bun:"grouping" json:"grouping" meta:"label:Grouping,help:Stores the grouping value for this record."`
	DecimalPoint string `bun:"decimal_point" json:"decimal_point" meta:"label:Decimal Point,help:Stores the decimal point value for this record."`
	ThousandsSep string `bun:"thousands_sep" json:"thousands_sep" meta:"label:Thousands Sep,help:Stores the thousands sep value for this record."`
	FlagImage    string `bun:"flag_image" json:"flag_image" meta:"label:Flag Image,help:Stores the flag image value for this record."`
	FlagImageURL string `bun:"flag_image_url" json:"flag_image_url" meta:"compute:_compute_flag_image_url,stored:false,label:Flag Image URL,help:Stores the computed value for flag image url."`
}

const ResLangModelName = "tbl.lang"

