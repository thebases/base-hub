// computeFlagImageURLResLang computes the flag image url res lang handled by this package.
func computeFlagImageURLResLang(ctx context.Context, records orm.RecordSet, _ orm.FieldMetadata) (map[string]any, error) {
	rows, err := loadResLangRows(ctx, records.IDs())
	if err != nil {
		return nil, err
	}
	out := make(map[string]any, len(rows))
	for _, row := range rows {
		out[strconv.FormatInt(row.ID, 10)] = resLangFlagImageURL(row)
	}
	return out, nil
}

func applyResLangDefaults(values map[string]any) {

	if _, exists := values["active"]; !exists {
		values["active"] = true
	}
	if _, exists := values["direction"]; !exists {
		values["direction"] = "ltr"
	}
	if _, exists := values["date_format"]; !exists {
		values["date_format"] = "%m/%d/%Y"
	}
	if _, exists := values["time_format"]; !exists {
		values["time_format"] = "%H:%M:%S"
	}
	if _, exists := values["week_start"]; !exists {
		values["week_start"] = "1"
	}
	if _, exists := values["grouping"]; !exists {
		values["grouping"] = "[]"
	}
	if _, exists := values["decimal_point"]; !exists {
		values["decimal_point"] = "."
	}
	if _, exists := values["thousands_sep"]; !exists {
		values["thousands_sep"] = ","
	}
}

func normalizeResLangClockFormat(values map[string]any) bool {
	timeFormat := strings.TrimSpace(stringValue(values["time_format"]))
	if timeFormat == "" {
		return false
	}
	normalized := strings.ReplaceAll(timeFormat, "%I", "%H")
	normalized = strings.ReplaceAll(normalized, "%p", "")
	normalized = strings.ReplaceAll(normalized, "%P", "")
	normalized = strings.Join(strings.Fields(normalized), " ")
	if normalized == timeFormat {
		return false
	}
	values["time_format"] = normalized
	return true
}

func normalizeResLangDirection(values map[string]any) {
	direction := strings.ToLower(strings.TrimSpace(fmt.Sprint(values["direction"])))
	if direction == "" {
		values["direction"] = "ltr"
		return
	}
	switch direction {
	case "left-to-right", "left_to_right", "left to right":
		values["direction"] = "ltr"
		return
	case "right-to-left", "right_to_left", "right to left":
		values["direction"] = "rtl"
		return
	}
	values["direction"] = direction
}

// validateResLangValues validates the res lang values handled by this package.
func validateResLangValues(values map[string]any) error {
	// Walk each string{"name", "code", "iso code", "direction", "date format", "time format", "week start", "grouping", "decimal point" entry in order so validation and side effects stay scoped to the current element.
	for _, key := range []string{"name", "code", "iso_code", "direction", "date_format", "time_format", "week_start", "grouping", "decimal_point"} {
		if !resLangHasTextValue(values[key]) {
			log.Errorf("tbl.lang %s is required", key)
			return orm.InvalidParamsf("tbl.lang %s is required", key)
		}
	}
	if direction := strings.TrimSpace(fmt.Sprint(values["direction"])); direction != "ltr" && direction != "rtl" {
		log.Errorf("tbl.lang direction must be ltr or rtl")
		return orm.InvalidParamsf("tbl.lang direction must be ltr or rtl")
	}
	dateFormat := strings.TrimSpace(fmt.Sprint(values["date_format"]))
	timeFormat := strings.TrimSpace(fmt.Sprint(values["time_format"]))
	for _, token := range resLangDisallowedFormatTokens {
		if strings.Contains(dateFormat, token) || strings.Contains(timeFormat, token) {
			log.Errorf("tbl.lang format token %s is not supported", token)
			return orm.InvalidParamsf("tbl.lang format token %s is not supported", token)
		}
	}
	return nil
}

func resLangHasTextValue(value any) bool {
	if value == nil {
		return false
	}
	return strings.TrimSpace(fmt.Sprint(value)) != ""
}

func resLangLikeClause(operator, value string) (string, any) {
	switch strings.TrimSpace(strings.ToLower(operator)) {
	case "=", "==":
		return "= ?", value
	case "=like", "like":
		return "LIKE ?", value
	default:
		return "ILIKE ?", "%" + value + "%"
	}
}

// applyResLangNumericSeparators applies the res lang numeric separators handled by this package.
func applyResLangNumericSeparators(text string, row ResLangRecord, grouping bool) string {
	parts := strings.SplitN(text, ".", 2)
	integerPart := parts[0]
	fractionPart := ""
	if len(parts) == 2 {
		fractionPart = parts[1]
	}
	if grouping && row.ThousandsSep != "" {
		sign := ""
		if strings.HasPrefix(integerPart, "-") {
			sign = "-"
			integerPart = strings.TrimPrefix(integerPart, "-")
		}
		grouped := make([]string, 0, len(integerPart)/3+1)
		for len(integerPart) > 3 {
			grouped = append(grouped, integerPart[len(integerPart)-3:])
			integerPart = integerPart[:len(integerPart)-3]
		}
		if integerPart != "" {
			grouped = append(grouped, integerPart)
		}
		for left, right := 0, len(grouped)-1; left < right; left, right = left+1, right-1 {
			grouped[left], grouped[right] = grouped[right], grouped[left]
		}
		integerPart = sign + strings.Join(grouped, row.ThousandsSep)
	}
	if fractionPart == "" {
		return integerPart
	}
	return integerPart + firstNonEmpty(row.DecimalPoint, ".") + fractionPart
}

func resLangPrecision(pattern string, fallback int) int {
	if dot := strings.Index(pattern, "."); dot >= 0 {
		digits := strings.TrimRight(pattern[dot+1:], string(pattern[len(pattern)-1]))
		if parsed, err := strconv.Atoi(strings.TrimSpace(digits)); err == nil && parsed >= 0 {
			return parsed
		}
	}
	return fallback
}

func resLangFlagImageURL(row ResLangRecord) string {
	if strings.TrimSpace(row.FlagImage) != "" {
		return "/web/image/tbl.lang/" + strconv.FormatInt(row.ID, 10) + "/flag_image"
	}
	iso := strings.ToLower(strings.TrimSpace(row.ISOCode))

	if iso == "" {
		iso = strings.ToLower(strings.TrimSpace(row.Code))
	}
	if iso == "" {
		return ""
	}
	return "/base/static/img/flags/" + iso + ".png"
}

// loadResLangRows loads the res lang rows handled by this package.
func loadResLangRows(ctx context.Context, ids []string) ([]ResLangRecord, error) {
	if len(ids) == 0 {
		return nil, nil
	}
	rows := []ResLangRecord{}
	if err := resLangSelectQuery(ctx, &rows).
		Where("id IN (?)", bun.In(idsToAny(ids))).
		Scan(ctx); err != nil {
		return nil, err
	}
	sort.SliceStable(rows, func(i, j int) bool { return rows[i].ID < rows[j].ID })
	return rows, nil
}

// loadSingletonResLangRow loads the singleton res lang row handled by this package.
func loadSingletonResLangRow(ctx context.Context, id string) (ResLangRecord, error) {
	rows, err := loadResLangRows(ctx, []string{id})
	if err != nil {
		return ResLangRecord{}, err
	}
	if len(rows) == 0 {
		log.Errorf("tbl.lang %s not found", id)
		return ResLangRecord{}, orm.NotFoundf("tbl.lang %s not found", id)
	}
	return rows[0], nil
}

func activeResLangByCode(ctx context.Context, code string) (ResLangRecord, bool, error) {
	code = strings.TrimSpace(code)
	if code == "" {
		return ResLangRecord{}, false, nil
	}
	rows := []ResLangRecord{}
	err := resLangSelectQuery(ctx, &rows).
		Where("code = ?", code).
		Where("active IS TRUE").
		Limit(1).
		Scan(ctx)
	if err != nil {
		return ResLangRecord{}, false, err
	}
	if len(rows) == 0 {
		return ResLangRecord{}, false, nil
	}
	return rows[0], true, nil
}

// resLangSelectQuery centralizes the storage binding for ad-hoc tbl.lang reads
// so package-level helpers stay aligned with the metadata-registered tbl_lang
// table instead of Bun's inferred struct-name table.
func resLangSelectQuery(ctx context.Context, model any) *bun.SelectQuery {
	return orm.BunDBFromContext(ctx).NewSelect().
		Model(model).
		ModelTableExpr("? AS ?", bun.Ident(resLangStorageTable), bun.Ident(resLangQueryAlias))
}

// ensureResLangNotInUse ensures the res lang not in use handled by this package.
func ensureResLangNotInUse(ctx context.Context, codes []string) error {
	if len(codes) == 0 {
		return nil
	}
	count, err := orm.BunDBFromContext(ctx).NewSelect().
		TableExpr("users").
		Where("language IN (?)", bun.In(codes)).
		Count(ctx)
	if err != nil {
		return err
	}
	if count > 0 {
		log.Errorf("tbl.lang cannot deactivate a language currently used by users")
		return orm.Conflictf("tbl.lang cannot deactivate a language currently used by users")
	}
	return nil
}

func argAt(args []any, index int) any {
	if index < 0 || index >= len(args) {
		return nil
	}
	return args[index]
}

func floatValueOrDefault(raw any, fallback float64) float64 {
	switch value := raw.(type) {
	case float64:
		return value
	case float32:
		return float64(value)
	case int:
		return float64(value)
	case int64:
		return float64(value)
	case string:
		parsed, err := strconv.ParseFloat(strings.TrimSpace(value), 64)
		if err == nil {
			return parsed
		}
	}
	return fallback
}

func boolValueOrDefault(raw any, fallback bool) bool {
	if raw == nil {
		return fallback
	}
	return boolValue(raw)
}
